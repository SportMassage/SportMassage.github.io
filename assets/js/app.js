const GA_ID = 'G-BDQZKYTE33';
const CONSENT_KEY = 'analytics_consent';
let analyticsLoaded = false;

function readConsent() {
    try { return localStorage.getItem(CONSENT_KEY); } catch (e) { return null; }
}

function storeConsent(value) {
    try { localStorage.setItem(CONSENT_KEY, value); } catch (e) { /* storage blocked: the choice lasts for this page view only */ }
}

// GA4 is loaded only after the visitor accepts (Consent Mode v2).
function loadAnalytics() {
    if (analyticsLoaded) return;
    analyticsLoaded = true;
    window['ga-disable-' + GA_ID] = false;
    gtag('consent', 'update', {
        analytics_storage: 'granted',
        ad_storage: 'denied',
        ad_user_data: 'denied',
        ad_personalization: 'denied'
    });
    gtag('js', new Date());
    gtag('config', GA_ID);
    const script = document.createElement('script');
    script.async = true;
    script.src = 'https://www.googletagmanager.com/gtag/js?id=' + GA_ID;
    document.head.appendChild(script);
}

function clearAnalyticsCookies() {
    const host = location.hostname;
    const domains = ['', host, '.' + host, '.' + host.split('.').slice(-2).join('.')];
    document.cookie.split(';').forEach(c => {
        const name = c.split('=')[0].trim();
        if (name !== '_ga' && !name.startsWith('_ga_')) return;
        domains.forEach(d => {
            document.cookie = name + '=; expires=Thu, 01 Jan 1970 00:00:00 GMT; path=/' + (d ? '; domain=' + d : '');
        });
    });
}

function setConsent(value) {
    storeConsent(value);
    const banner = document.getElementById('analytics-notice');
    if (banner) banner.hidden = true;
    if (value === 'granted') {
        loadAnalytics();
        return;
    }
    if (analyticsLoaded) {
        window['ga-disable-' + GA_ID] = true;
        gtag('consent', 'update', { analytics_storage: 'denied' });
        analyticsLoaded = false;
    }
    clearAnalyticsCookies();
}

function initConsent() {
    // Browser extensions and built-in cookie-dialog blockers (e.g. Opera) can hide or remove
    // these elements, so every lookup is optional. Without a banner no choice can be made,
    // and analytics simply stays off.
    const banner = document.getElementById('analytics-notice');
    const bind = (id, handler) => {
        const el = document.getElementById(id);
        if (el) el.addEventListener('click', handler);
    };
    bind('analytics-accept', () => setConsent('granted'));
    bind('analytics-reject', () => setConsent('denied'));
    bind('analytics-settings-btn', () => { if (banner) banner.hidden = false; });

    const saved = readConsent();
    if (saved === 'granted') loadAnalytics();
    else if (saved !== 'denied' && banner) banner.hidden = false;
}

// The Google Maps iframe is created only after a click, so Google gets nothing before that.
function initMapPlaceholder() {
    const btn = document.getElementById('map-load-btn');
    const box = document.getElementById('map-box');
    if (!btn || !box) return;
    btn.addEventListener('click', () => {
        const frame = document.createElement('iframe');
        frame.title = 'Google Maps Kazimierzowska 69 Warszawa';
        frame.src = 'https://maps.google.com/maps?q=Kazimierzowska+69,+Warszawa&hl=' + encodeURIComponent(document.documentElement.lang || 'pl') + '&z=15&output=embed';
        frame.className = 'w-full h-full border-0';
        frame.allowFullscreen = true;
        box.replaceChildren(frame);
    });
}

function trackEvent(eventName, params = {}) {
    if (analyticsLoaded && typeof window.gtag === 'function') {
        window.gtag('event', eventName, params);
    }
}

function getElementLocation(element) {
    const section = element.closest('section');
    if (section && section.id) return section.id;
    if (element.closest('header')) return 'header';
    if (element.closest('footer')) return 'footer';
    return 'page';
}

// Every language has its own pre-translated page (generated by scripts/build-site.mjs), so there
// is no runtime translation. The only language logic here is remembering an explicit choice and
// offering a link to the visitor's preferred language. The build embeds the banner texts and the
// URL of this same page in every language as JSON in #lang-data.
const LANG_KEY = 'preferred_lang';
const LANG_DISMISS_KEY = 'lang_suggest_dismissed';

function readStorage(key) {
    try { return localStorage.getItem(key); } catch (e) { return null; }
}

function writeStorage(key, value) {
    try { localStorage.setItem(key, value); } catch (e) { /* storage blocked */ }
}

// An explicit choice (language switcher or banner link) wins over the browser's languages.
// Returns a locale key (pl, ua, ru, en) or null when nothing matches.
function detectPreferredLanguage(supported) {
    const saved = readStorage(LANG_KEY);
    if (saved && supported.includes(saved)) return saved;

    const browserLangs = navigator.languages || [navigator.language || ''];
    for (const raw of browserLangs) {
        const l = (raw || '').toLowerCase();
        let key = null;
        if (l.startsWith('pl')) key = 'pl';
        else if (l.startsWith('uk')) key = 'ua';
        else if (l.startsWith('ru') || l.startsWith('be')) key = 'ru';
        else if (l.startsWith('en')) key = 'en';
        if (key && supported.includes(key)) return key;
    }
    return null;
}

function initLangSuggest() {
    // Every lookup is optional: blockers or a stale cached page must not break the rest of the script.
    const banner = document.getElementById('lang-suggest');
    const text = document.getElementById('lang-suggest-text');
    const go = document.getElementById('lang-suggest-go');
    const close = document.getElementById('lang-suggest-close');
    const dataEl = document.getElementById('lang-data');
    if (!banner || !text || !go || !dataEl || readStorage(LANG_DISMISS_KEY)) return;

    let data;
    try { data = JSON.parse(dataEl.textContent); } catch (e) { return; }
    if (!data || !data.langs) return;

    const target = detectPreferredLanguage(Object.keys(data.langs));
    if (!target || target === data.current) return;

    const info = data.langs[target];
    banner.lang = info.htmlLang;
    text.textContent = info.text;
    go.textContent = info.go;
    go.href = info.url;
    go.hreflang = info.htmlLang;
    go.dataset.lang = target;
    if (close) {
        close.setAttribute('aria-label', info.close);
        close.addEventListener('click', () => {
            banner.hidden = true;
            writeStorage(LANG_DISMISS_KEY, '1');
        });
    }
    banner.hidden = false;
}

document.addEventListener('DOMContentLoaded', () => {
    const menuBtn = document.getElementById('mobile-menu-btn');
    const mobileMenu = document.getElementById('mobile-menu');

    if (menuBtn && mobileMenu) {
        menuBtn.addEventListener('click', () => {
            const isHidden = mobileMenu.classList.toggle('hidden');
            menuBtn.setAttribute('aria-expanded', String(!isHidden));
        });

        mobileMenu.querySelectorAll('a').forEach(link => {
            link.addEventListener('click', () => {
                mobileMenu.classList.add('hidden');
                menuBtn.setAttribute('aria-expanded', 'false');
            });
        });
    }

    document.addEventListener('click', (e) => {
        const link = e.target.closest('a');
        if (!link) return;

        // Language switcher and banner links: remember the choice (the navigation itself is a normal link)
        if (link.dataset.lang) {
            writeStorage(LANG_KEY, link.dataset.lang);
            trackEvent('change_language', { selected_language: link.dataset.lang });
        }

        const href = link.getAttribute('href') || '';
        const location = getElementLocation(link);

        if (href.includes('wa.me')) {
            trackEvent('click_whatsapp', {
                location: location
            });
        }

        else if (href.includes('t.me/Dmitry_waw')) {
            trackEvent('click_telegram_dm', {
                location: location
            });
        }

        else if (href.includes('t.me/Massage_ww')) {
            trackEvent('click_telegram_channel', {
                location: location
            });
        }

        else if (href.startsWith('tel:')) {
            trackEvent('click_phone', {
                location: location
            });
        }

        else if (href.includes('maps.app.goo.gl')) {
            trackEvent('click_maps', {
                location: location
            });
        }
    });

    initLangSuggest();
    initMapPlaceholder();
    initConsent();
});